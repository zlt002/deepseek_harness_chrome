test('brief suggestions are registered before forwarding to the bound Harness conversation', async () => {
  const source = await readFile(new URL('../background.ts', import.meta.url), 'utf8')
  const handler = source.slice(source.indexOf("if (request.type === 'prototype-studio-suggest-brief/v1')"), source.indexOf("if (request.type === 'prototype-studio-prompt/v1')"))
  const begin = handler.indexOf('PROTOTYPE_STUDIO_BEGIN_BRIEF_SUGGESTION_PATH')
  const forward = handler.indexOf("type: 'prototype-studio-brief-suggestion-forward/v1'")
  assert.ok(begin >= 0 && forward > begin)
  assert.match(handler, /snapshot\.designConfirmed !== true/)
  assert.match(handler, /snapshot\.generationAttempt !== undefined/)
  assert.match(handler, /projectId: authorization\.projectId, sessionId: authorization\.sessionId, requestId: request\.requestId/)
})

