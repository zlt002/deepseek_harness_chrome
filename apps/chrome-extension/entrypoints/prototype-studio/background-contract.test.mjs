test('Prototype Studio begins before forwarding and cancels a failed forward', async () => {
  const source = await readFile(new URL('../background.ts', import.meta.url), 'utf8')
  const promptHandler = source.slice(source.indexOf("if (request.type === 'prototype-studio-prompt/v1')"), source.indexOf("if (request.type === 'save-browser-target-settings')"))
  const begin = promptHandler.indexOf('PROTOTYPE_STUDIO_BEGIN_GENERATION_PATH')
  const forward = promptHandler.indexOf("type: 'prototype-studio-prompt-forward/v1'")
  const cancel = promptHandler.indexOf('PROTOTYPE_STUDIO_CANCEL_GENERATION_PATH')
  assert.ok(begin >= 0 && forward > begin && cancel > forward)
  assert.match(promptHandler, /requestId: request\.requestId, expectedRevisionId: expectedRevisionId \?\? null/)
  assert.match(promptHandler, /prompt: request\.prompt/)
  assert.match(promptHandler, /首次生成前请先保存并确认产品需求清单/)
  assert.match(promptHandler, /briefChanged && expectedRevisionId === undefined/)
  assert.match(promptHandler, /briefChanged && selection !== undefined/)
  assert.match(promptHandler, /productBrief: generationBrief/)
  assert.match(promptHandler, /未能将本次原型生成请求交给 Harness，已取消。/)
})
